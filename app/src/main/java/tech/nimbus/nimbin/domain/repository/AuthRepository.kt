package tech.nimbus.nimbin.domain.repository

import kotlinx.coroutines.flow.Flow

/**
 * Sealed class для представления результатов операций аутентификации.
 *
 * Обеспечивает типобезопасную обработку состояний асинхронных операций
 * с возможностью передачи данных об успехе, ошибках и процессе загрузки.
 *
 * @param T Тип данных при успешном выполнении операции
 *
 * @see AuthRepository
 * @author NimBin Team
 * @since 1.0
 */
sealed class AuthResult<out T> {
    /**
     * Успешное выполнение операции аутентификации.
     *
     * @param data Результат операции (например, JWT токен или данные пользователя)
     */
    data class Success<out T>(val data: T) : AuthResult<T>()

    /**
     * Ошибка при выполнении операции аутентификации.
     *
     * @param message Человеко-читаемое описание ошибки для отображения в UI
     * @param exception Исходное исключение для отладки (опционально)
     */
    data class Error(val message: String, val exception: Throwable? = null) : AuthResult<Nothing>()

    /**
     * Состояние выполнения операции аутентификации.
     * Используется для отображения индикаторов загрузки в UI.
     */
    object Loading : AuthResult<Nothing>()
}

/**
 * Репозиторий для управления аутентификацией пользователей в системе NimBin.
 *
 * Обеспечивает абстракцию над источниками данных аутентификации (API, локальное хранилище)
 * и предоставляет единый интерфейс для всех операций, связанных с управлением пользователями.
 *
 * ## Основные обязанности:
 * - Выполнение аутентификации пользователей (вход/регистрация/выход)
 * - Управление JWT токенами (сохранение/получение/удаление)
 * - Кэширование данных пользователя
 * - Обработка ошибок аутентификации и их преобразование в понятный формат
 *
 * ## Паттерны использования:
 * Все методы возвращают `Flow<AuthResult<T>>` для реактивного программирования:
 * - `Loading` - показывается индикатор загрузки
 * - `Success` - операция выполнена, UI обновляется данными
 * - `Error` - показывается сообщение об ошибке пользователю
 *
 * ## Безопасность:
 * - JWT токены хранятся в зашифрованном DataStore
 * - Пароли никогда не кэшируются локально
 * - Автоматическая очистка данных при logout
 *
 * @see AuthResult
 * @see LoginUseCase
 * @see RegisterUseCase
 * @see LogoutUseCase
 *
 * @author NimBin Team
 * @since 1.0
 */
interface AuthRepository {
    /**
     * Выполняет аутентификацию пользователя в системе.
     *
     * Отправляет учетные данные на сервер для проверки и получает JWT токен
     * при успешной аутентификации. Токен автоматически сохраняется для
     * последующих API вызовов.
     *
     * @param email Email адрес или username пользователя.
     *              Поддерживается как полный email, так и простой username.
     * @param password Пароль пользователя в открытом виде.
     *                 Шифрование происходит на стороне сервера.
     *
     * @return Flow<AuthResult<String>> Поток состояний аутентификации:
     *         - Loading: процесс отправки запроса на сервер
     *         - Success: содержит JWT токен для API запросов
     *         - Error: ошибка аутентификации (неверные данные, сеть и т.д.)
     *
     * ## Возможные ошибки:
     * - "Неверные учетные данные" - неправильный email/пароль
     * - "Аккаунт заблокирован" - превышено количество попыток входа
     * - "Сетевая ошибка" - проблемы с подключением к серверу
     */
    fun login(email: String, password: String): Flow<AuthResult<String>>

    /**
     * Регистрирует нового пользователя в системе.
     *
     * Создает новый аккаунт пользователя с проверкой уникальности данных.
     * При успешной регистрации пользователь может сразу войти в систему.
     *
     * @param username Уникальное имя пользователя (3-30 символов).
     *                 Используется для входа в систему и отображения в заметках.
     * @param email Уникальный email адрес для восстановления доступа
     *              и уведомлений.
     * @param password Пароль (минимум 6 символов).
     *                 Рекомендуется использовать сложные пароли.
     *
     * @return Flow<AuthResult<Unit>> Поток состояний регистрации:
     *         - Loading: процесс создания аккаунта на сервере
     *         - Success: аккаунт создан, можно выполнять вход
     *         - Error: ошибка регистрации (данные заняты, валидация и т.д.)
     *
     * ## Возможные ошибки:
     * - "Пользователь с таким email уже существует"
     * - "Имя пользователя уже занято"
     * - "Слабый пароль" - не соответствует требованиям безопасности
     * - "Некорректный email формат"
     */
    fun register(username: String, email: String, password: String): Flow<AuthResult<Unit>>

    /**
     * Выполняет выход пользователя из системы.
     *
     * Очищает все локально сохраненные данные пользователя (JWT токен,
     * кэш профиля) и уведомляет сервер о завершении сессии.
     *
     * @return Flow<AuthResult<Unit>> Поток состояний выхода:
     *         - Loading: процесс очистки данных
     *         - Success: пользователь вышел, можно показать экран входа
     *         - Error: ошибка выхода (обычно не критична для UI)
     *
     * ## Поведение:
     * - Локальные данные очищаются независимо от ответа сервера
     * - Ошибки сети при logout не блокируют локальную очистку
     * - После вызова все API запросы будут выполняться как анонимные
     */
    fun logout(): Flow<AuthResult<Unit>>

    /**
     * Provides a flow that emits the current authentication token, or null if logged out.
     */
    fun getAuthToken(): Flow<String?>

    /**
     * Saves the authentication token to persistent storage.
     * @param token The token to save.
     */
    suspend fun saveAuthToken(token: String)

    /**
     * Clears the authentication token from persistent storage.
     */
    suspend fun clearAuthToken()
}
